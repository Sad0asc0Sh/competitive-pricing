"use strict";

require("dotenv/config");
var _index = require("./index");
/**
 * این سیستم عمداً هیچ داده نمونه/ساختگی (seed) ندارد.
 *
 * قبلاً این فایل ۶ محصول نمونه با منبع شبیه‌سازی‌شده (mock) وارد دیتابیس
 * می‌کرد؛ آن منبع به‌طور کامل حذف شده است تا هیچ تصمیم قیمتی بر اساس داده
 * جعلی گرفته نشود.
 *
 * برای پرکردن سیستم با داده واقعی یکی از این دو مسیر را استفاده کنید:
 *  ۱. ایمپورت محصولات واقعی فروشگاه از MongoDB:
 *       node scripts/import-mongo-products.cjs
 *  ۲. افزودن دستی محصول از پنل (صفحه «محصولات») با منبع ترب.
 *
 * داده‌های پیش‌فرض واقعی سیستم (پروفایل قیمت‌گذاری، ۳ کمپین تخفیف،
 * زمان‌بندی استعلام و کانکتورهای فروشگاه) به‌صورت خودکار و idempotent
 * در ‎ensureDefaults()‎ ساخته می‌شوند و نیازی به seed ندارند.
 */
async function main() {
  console.log("seed: هیچ داده نمونه‌ای وارد نشد (سیاست سیستم واقعی). برای ایمپورت محصولات واقعی: node scripts/import-mongo-products.cjs");
  await _index.pool.end();
}
main().catch(e => {
  console.error(e);
  process.exit(1);
});